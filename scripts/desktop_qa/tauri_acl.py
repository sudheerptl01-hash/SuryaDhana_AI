"""Static resolver for the Tauri v2 ACL of desktop/src-tauri (capabilities → permissions → commands).

Used by tests/integration/test_desktop_contract.py to prove least privilege (PLAN §5, AC-11): the capability
for the remote origin ``http://127.0.0.1:8010`` must resolve to exactly the nine ``shell_*`` commands.

Resolution sources, most authoritative first:

1. ``gen/schemas/acl-manifests.json`` written by ``tauri-build`` (every plugin + ``__app-acl__`` for the app's
   own commands once ``build.rs`` declares an ``AppManifest``)
2. the app's own permission files ``permissions/**/*.toml`` (``[[permission]]``, ``[[set]]``, ``[default]``)
3. the autogenerated app permissions ``allow-<cmd>`` / ``deny-<cmd>`` for each command in
   ``AppManifest::commands(&[...])`` (``_`` → ``-``, as tauri-build slugifies them)

Identifier grammar (Tauri v2): ``<plugin>:<perm>``, ``core:<module>:<perm>``, or a bare ``<perm>`` for the app.
Members of a set/default without ``:`` are relative to the set's plugin. App commands resolve to their bare
name (``shell_info``); plugin commands to ``plugin:<name>|<cmd>`` (the runtime IPC key).
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import tomllib

APP_KEY = "__app-acl__"


class AclError(ValueError):
    """An identifier that cannot be resolved (typo, missing plugin, or stale gen/schemas)."""


@dataclass
class Acl:
    manifests: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def load(cls, src_tauri: Path) -> Acl:
        manifests: dict[str, Any] = {}
        gen = src_tauri / "gen" / "schemas" / "acl-manifests.json"
        if gen.is_file():
            manifests = json.loads(gen.read_text())
        app = manifests.setdefault(APP_KEY, {"default_permission": None, "permissions": {}, "permission_sets": {}})
        app.setdefault("permissions", {})
        app.setdefault("permission_sets", {})
        for toml in sorted((src_tauri / "permissions").rglob("*.toml")) if (src_tauri / "permissions").is_dir() else []:
            data = tomllib.loads(toml.read_text())
            for perm in data.get("permission", []):
                app["permissions"].setdefault(perm["identifier"], {"identifier": perm["identifier"],
                                                                   "commands": perm.get("commands", {})})
            for s in data.get("set", []):
                app["permission_sets"].setdefault(s["identifier"], {"identifier": s["identifier"],
                                                                     "permissions": s.get("permissions", [])})
            if "default" in data and not app.get("default_permission"):
                app["default_permission"] = {"identifier": "default", "permissions": data["default"].get("permissions", [])}
        for cmd in app_manifest_commands(src_tauri) or []:
            slug = cmd.replace("_", "-")
            app["permissions"].setdefault(f"allow-{slug}", {"identifier": f"allow-{slug}", "commands": {"allow": [cmd], "deny": []}})
            app["permissions"].setdefault(f"deny-{slug}", {"identifier": f"deny-{slug}", "commands": {"allow": [], "deny": [cmd]}})
        return cls(manifests)

    def resolve(self, identifier: str, _seen: frozenset[str] = frozenset()) -> set[str]:
        """Commands allowed by ``identifier`` (recursing through sets and defaults)."""
        if identifier in _seen:
            raise AclError(f"permission cycle at {identifier}")
        key, perm = split_identifier(identifier)
        man = self.manifests.get(key)
        if man is None:
            raise AclError(f"unknown plugin '{key}' for permission '{identifier}'")
        seen = _seen | {identifier}

        def members(ids: list[str]) -> set[str]:
            out: set[str] = set()
            for m in ids:
                out |= self.resolve(m if ":" in m or key == APP_KEY else f"{key}:{m}", seen)
            return out

        if perm == "default":
            d = man.get("default_permission")
            if not d:
                raise AclError(f"'{identifier}': plugin has no default permission")
            return members(d.get("permissions", []))
        sets = man.get("permission_sets") or {}
        if perm in sets:
            return members(sets[perm].get("permissions", []))
        perms = man.get("permissions") or {}
        if perm in perms:
            allow = (perms[perm].get("commands") or {}).get("allow") or []
            return {qualify(key, c) for c in allow}
        raise AclError(f"unknown permission '{identifier}'")


def split_identifier(identifier: str) -> tuple[str, str]:
    """``core:event:allow-listen`` → (``core:event``, ``allow-listen``); ``allow-x`` → (``__app-acl__``, ``allow-x``)."""
    if ":" not in identifier:
        return APP_KEY, identifier
    key, perm = identifier.rsplit(":", 1)
    return key, perm


def qualify(key: str, command: str) -> str:
    if key == APP_KEY:
        return command
    if key.startswith("core:"):
        return f"plugin:{key[5:]}|{command}"
    return f"plugin:{key}|{command}"


def permission_id(entry: Any) -> str:
    """A capability permission entry is a string or ``{"identifier": ..., "allow"/"deny": scopes}``."""
    if isinstance(entry, str):
        return entry
    if isinstance(entry, dict) and isinstance(entry.get("identifier"), str):
        return entry["identifier"]
    raise AclError(f"malformed permission entry {entry!r}")


# Placeholders D2's runtime capability uses (src/lib.rs add_remote_capability substitutes them with the configured
# ui_url origin and its localhost/127.0.0.1 alias before app.add_capability). Mirrored here for the default
# ui_url so the test evaluates exactly what the app grants at runtime.
RUNTIME_PLACEHOLDERS = {"__UI_ORIGIN_ALIAS__": "http://localhost:8010", "__UI_ORIGIN__": "http://127.0.0.1:8010"}


def load_capabilities(src_tauri: Path, placeholders: dict[str, str] | None = None) -> list[dict[str, Any]]:
    """Capability objects from ``capabilities/*.json|*.toml``, the runtime-added ``capabilities-runtime/*.json``
    (placeholders substituted, see ``RUNTIME_PLACEHOLDERS``) and inline ones in tauri.conf.json."""
    subs = RUNTIME_PLACEHOLDERS if placeholders is None else placeholders
    caps: list[dict[str, Any]] = []
    for dirname in ("capabilities", "capabilities-runtime"):
        cap_dir = src_tauri / dirname
        if not cap_dir.is_dir():
            continue
        for f in sorted(cap_dir.iterdir()):
            text = f.read_text() if f.suffix in (".json", ".toml") else None
            if text is None:
                continue
            if dirname == "capabilities-runtime":
                for k, v in subs.items():   # longest placeholder first (dict order above)
                    text = text.replace(k, v)
            obj = json.loads(text) if f.suffix == ".json" else tomllib.loads(text)
            for c in obj if isinstance(obj, list) else [obj]:
                caps.append({**c, "_file": f"{dirname}/{f.name}"})
    conf = src_tauri / "tauri.conf.json"
    if conf.is_file():
        inline = ((json.loads(conf.read_text()).get("app") or {}).get("security") or {}).get("capabilities") or []
        caps += [{**c, "_file": "tauri.conf.json"} for c in inline if isinstance(c, dict)]
    return caps


def is_remote(cap: dict[str, Any]) -> bool:
    return bool((cap.get("remote") or {}).get("urls"))


def app_manifest_commands(src_tauri: Path) -> list[str] | None:
    """Command names declared by ``AppManifest::new().commands(&[...])`` in build.rs (None if not declared)."""
    build = src_tauri / "build.rs"
    if not build.is_file():
        return None
    text = build.read_text()
    m = re.search(r"AppManifest::new\(\)\s*\.commands\(\s*&\s*\[(.*?)\]\s*\)", text, re.DOTALL)
    if not m:
        m = re.search(r"\.commands\(\s*&\s*\[(.*?)\]\s*\)", text, re.DOTALL) if "app_manifest" in text else None
    if not m:
        # a const list referenced by .commands(COMMANDS)
        ref = re.search(r"\.commands\(\s*&?\s*([A-Z_][A-Z0-9_]*)\s*\)", text)
        if ref:
            m = re.search(rf"const\s+{ref.group(1)}\s*:[^=]*=\s*&?\[(.*?)\]", text, re.DOTALL)
    if not m:
        return None
    return re.findall(r'"([a-z_][a-z0-9_]*)"', m.group(1))


def registered_handlers(src_tauri: Path) -> list[str] | None:
    """Command names in every ``generate_handler![...]`` of src/*.rs (last path segment), or None."""
    names: list[str] = []
    found = False
    for f in sorted((src_tauri / "src").rglob("*.rs")):
        for m in re.finditer(r"generate_handler!\s*\[(.*?)\]", f.read_text(), re.DOTALL):
            found = True
            body = re.sub(r"//[^\n]*", "", m.group(1))
            names += [seg.strip().split("::")[-1] for seg in body.split(",") if seg.strip()]
    return names if found else None
