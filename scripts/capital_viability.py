"""
Capital-viability report: yearly cost drag of each trading style at each capital
level, under each broker profile (shared/trading_costs.py).

A style is only worth running if its expected gross edge clearly exceeds this drag.

Usage:
    /Users/sudheer/Desktop/jupyter_env/bin/python scripts/capital_viability.py
Output: reports/costs/CAPITAL_VIABILITY.md
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from shared.trading_costs import PROFILES, CostModel, profile_from_env  # noqa: E402

CAPITALS = [10_000, 100_000, 250_000, 500_000, 1_000_000]


@dataclass(frozen=True)
class Style:
    name: str
    n_positions: int
    rebalances_per_year: float
    turnover: float          # share of positions replaced per rebalance
    note: str


STYLES = [
    Style("Current system: 5-day holds, 5 names", 5, 52, 1.0, "what the repo was built for"),
    Style("Monthly momentum, 10 names", 10, 12, 0.4, "with buffer bands"),
    Style("Monthly momentum, 20 names", 20, 12, 0.3, "with buffer bands"),
    Style("Semi-annual momentum, 30 names", 30, 2, 0.5, "NSE Momentum-30 cadence"),
    Style("Core ETFs, monthly regime switch", 2, 12, 0.15, "a switch moves the whole book ~2×/yr"),
]


def prime_payback(style: Style = STYLES[2]) -> list[str]:
    """Does a one-time ICICI Prime plan pay for itself vs the default MoneySaver?"""
    base = CostModel(PROFILES["icici_moneysaver"])
    rows = [f"## Is an ICICI Prime plan worth it? ({style.name}, {style.note})", "",
            "Yearly charges in ₹ and months until the one-time fee (+18% GST) is recovered vs MoneySaver.", "",
            "| Capital | MoneySaver ₹/yr | " + " | ".join(
                f"{k.replace('icici_prime_', 'Prime ₹')} ₹/yr (payback)" for k in PROFILES if k.startswith("icici_prime")) + " |",
            "|---|---|" + "---|" * sum(k.startswith("icici_prime") for k in PROFILES)]
    for cap in CAPITALS[1:]:
        yearly = lambda m: m.annual_drag_pct(cap, style.n_positions, style.rebalances_per_year, style.turnover) * cap / 100
        b = yearly(base)
        cells = []
        for k, prof in PROFILES.items():
            if not k.startswith("icici_prime"):
                continue
            c = yearly(CostModel(prof))
            saving = b - c
            fee = prof.one_time_fee * 1.18
            pay = f"{fee / saving * 12:.0f} mo" if saving > 0 else "never"
            cells.append(f"₹{c:,.0f} ({pay})")
        rows.append(f"| ₹{cap:,.0f} | ₹{b:,.0f} | " + " | ".join(cells) + " |")
    return rows + [""]


def main() -> None:
    out = ROOT / "reports" / "costs"
    out.mkdir(parents=True, exist_ok=True)
    profiles = [profile_from_env()] + [p for k, p in PROFILES.items() if k != profile_from_env().name]
    lines = ["# Capital viability: yearly cost drag by trading style", "",
             "Cost drag = % of your capital lost to charges per year (brokerage, STT, stamp, exchange,",
             "SEBI, DP, GST). A style needs expected gross edge well above this number to make money.",
             "Generated by `scripts/capital_viability.py` from `shared/trading_costs.py`.", ""]
    for prof in profiles:
        m = CostModel(prof)
        lines += [f"## Broker profile: `{prof.name}`, {prof.note or ''}", "",
                  "| Style | " + " | ".join(f"₹{c:,.0f}" for c in CAPITALS) + " |",
                  "|---|" + "---|" * len(CAPITALS)]
        for st in STYLES:
            cells = []
            for cap in CAPITALS:
                d = m.annual_drag_pct(cap, st.n_positions, st.rebalances_per_year, st.turnover)
                cells.append(f"**{d:.1f}%**" if d > 5 else f"{d:.1f}%")
            lines.append(f"| {st.name} ({st.note}) | " + " | ".join(cells) + " |")
        lines += ["", "Round trip on one position:", "",
                  "| Position | " + " | ".join(f"₹{v:,.0f}" for v in (1_500, 10_000, 50_000, 100_000, 500_000)) + " |",
                  "|---|" + "---|" * 5,
                  "| Cost | " + " | ".join(f"{m.round_trip_pct(v):.2f}%" for v in
                                           (1_500, 10_000, 50_000, 100_000, 500_000)) + " |", ""]
        for tgt in (1.0, 0.5, 0.3):
            mp = m.min_position_for(tgt)
            lines.append(f"- Smallest position with round trip ≤ {tgt}%: "
                         + (f"₹{mp:,.0f}" if mp else "not reachable on this plan"))
        lines.append("")
    lines += prime_payback()
    (out / "CAPITAL_VIABILITY.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
